import { build } from 'esbuild';
import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
await build({ entryPoints: ['src/components/businessModel.ts'], outfile: '.build/model.cjs', bundle: true, platform: 'node', format: 'cjs' });
const require = createRequire(import.meta.url);
const { initialBusiness, businessReducer: reduce, businessSnapshot: snapshot } = require('../.build/model.cjs');
let state = reduce(initialBusiness, { type: 'quantity', value: 4 });
state = reduce(state, { type: 'credit', value: true });
assert.equal(snapshot(state).amount, 2360);
state = reduce(state, { type: 'delivery' });
assert.equal(snapshot(state).stock, 50);
for (let i = 0; i < 3; i++) state = reduce(state, { type: 'next' });
assert.equal(snapshot(state).stock, 46);
assert.equal(snapshot(state).balance, 14200);
assert.equal(reduce(state, { type: 'quantity', value: 8 }).quantity, 4);
assert.equal(reduce(state, { type: 'credit', value: false }).credit, true);
state = reduce(state, { type: 'next' });
assert.equal(snapshot(state).balance, 16560);
state = reduce(state, { type: 'next' });
assert.equal(snapshot(state).sales, 27210);
assert.equal(snapshot(state).invoices, 33);
for (let i = 0; i < 5; i++) state = reduce(state, { type: 'next' });
assert.equal(snapshot(state).stock, 46);
assert.equal(snapshot(state).balance, 16560);
assert.equal(snapshot(state).invoices, 33);
assert.equal(snapshot(reduce(state, { type: 'delivery' })).stock, 46);
state = reduce(state, { type: 'reset' });
for (let i = 0; i < 5; i++) state = reduce(state, { type: 'next' });
assert.equal(snapshot(state).balance, 14200);
assert.equal(snapshot(state).payment, 'Payment recorded');
assert.deepEqual(reduce(state, { type: 'reset' }), initialBusiness);
assert.equal(reduce(initialBusiness, { type: 'quantity', value: 99 }).quantity, 8);
assert.equal(reduce(initialBusiness, { type: 'quantity', value: -1 }).quantity, 1);
assert.equal(reduce(initialBusiness, { type: 'attendance' }).present, false);
console.log('Business model passed: quantity/credit locking, stock receipts, phased credit/report updates, paid sale, completion idempotency, bounded quantity, attendance and reset.');
